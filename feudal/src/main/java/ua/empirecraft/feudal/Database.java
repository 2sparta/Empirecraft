package ua.empirecraft.feudal;

import java.sql.*;
import java.util.*;

/** One connection, confined to the Bukkit main thread. All state changes use a transaction. */
public final class Database implements AutoCloseable {
    private final Connection connection;
    private boolean transaction;
    public Database(String url) throws SQLException { this(url,null); }
    public Database(String url,String migrationBackup) throws SQLException {
        connection = DriverManager.getConnection(url, "sa", "");
        for (String ddl : List.of(
            "CREATE TABLE IF NOT EXISTS schema_version (version INT PRIMARY KEY)",
            "CREATE TABLE IF NOT EXISTS estates (id VARCHAR(80) PRIMARY KEY, kind VARCHAR(16), name VARCHAR(64), nation VARCHAR(80), lord VARCHAR(36), active BOOLEAN NOT NULL)",
            "CREATE TABLE IF NOT EXISTS ties (child VARCHAR(80) PRIMARY KEY, parent VARCHAR(80) NOT NULL, contract VARCHAR(36))",
            "CREATE TABLE IF NOT EXISTS proposals (id VARCHAR(36) PRIMARY KEY, action VARCHAR(16), child VARCHAR(80), parent VARCHAR(80), nominee VARCHAR(36), amount BIGINT, code VARCHAR(8), autonomy VARCHAR(16), military VARCHAR(16), expires BIGINT, duration_days INT, fingerprint CLOB, required CLOB, signed CLOB)",
            "CREATE TABLE IF NOT EXISTS contracts (id VARCHAR(36) PRIMARY KEY, child VARCHAR(80), parent VARCHAR(80), amount BIGINT, code VARCHAR(8), autonomy VARCHAR(16), military VARCHAR(16), next_due BIGINT, ends BIGINT, active BOOLEAN)",
            "CREATE TABLE IF NOT EXISTS currencies (code VARCHAR(8) PRIMARY KEY, name VARCHAR(64), symbol VARCHAR(8), issuer VARCHAR(80) UNIQUE, supply BIGINT NOT NULL CHECK(supply >= 0))",
            "CREATE TABLE IF NOT EXISTS accounts (owner VARCHAR(100), code VARCHAR(8), balance BIGINT NOT NULL CHECK(balance >= 0), PRIMARY KEY(owner, code))",
            "CREATE TABLE IF NOT EXISTS invoices (id VARCHAR(100) PRIMARY KEY, contract VARCHAR(36), child VARCHAR(80), parent VARCHAR(80), code VARCHAR(8), amount BIGINT, paid BIGINT, due BIGINT, CHECK(paid >= 0 AND paid <= amount))",
            "CREATE TABLE IF NOT EXISTS grants (person VARCHAR(36), nation VARCHAR(80), rank VARCHAR(16), PRIMARY KEY(person, nation))",
            "CREATE TABLE IF NOT EXISTS charters (person VARCHAR(36) PRIMARY KEY, nation VARCHAR(80), parent VARCHAR(80), expires BIGINT)",
            "CREATE TABLE IF NOT EXISTS pending_foundings (person VARCHAR(36) PRIMARY KEY, name VARCHAR(64), created BIGINT)",
            "CREATE TABLE IF NOT EXISTS vault_ops (id VARCHAR(36) PRIMARY KEY, actor VARCHAR(36), direction VARCHAR(16), amount BIGINT, status VARCHAR(16), created BIGINT)",
            "CREATE TABLE IF NOT EXISTS audit (seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at_time BIGINT, actor VARCHAR(80), event VARCHAR(32), detail CLOB)",
            "CREATE INDEX IF NOT EXISTS invoices_child ON invoices(child, due)",
            "CREATE INDEX IF NOT EXISTS audit_time ON audit(at_time)")) execute(ddl);
        execute("CREATE TABLE IF NOT EXISTS registration_outbox(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_key VARCHAR(180) UNIQUE,kind VARCHAR(10),reference VARCHAR(100),payload CLOB,state VARCHAR(12) DEFAULT 'PENDING',attempts INT DEFAULT 0,next_attempt BIGINT,created BIGINT,channel VARCHAR(20) DEFAULT '',message_id VARCHAR(20) DEFAULT '',last_status INT DEFAULT 0)");
        execute("CREATE INDEX IF NOT EXISTS registration_delivery ON registration_outbox(state,next_attempt,id)");
        execute("CREATE TABLE IF NOT EXISTS item_ops(id VARCHAR(36) PRIMARY KEY, kind VARCHAR(16), related VARCHAR(36), quantity BIGINT, actor VARCHAR(36), status VARCHAR(16), created BIGINT)");
        execute("CREATE TABLE IF NOT EXISTS item_participants(op VARCHAR(36), person VARCHAR(36), before_items CLOB, after_items CLOB, PRIMARY KEY(op,person))");
        execute("CREATE TABLE IF NOT EXISTS item_payments(op VARCHAR(36), source VARCHAR(100), target VARCHAR(100), code VARCHAR(8), amount BIGINT, PRIMARY KEY(op,source,code))");
        execute("CREATE INDEX IF NOT EXISTS item_participants_person ON item_participants(person)");
        var versions = query("SELECT version FROM schema_version");
        long version=versions.isEmpty()?0:number(versions.get(0),"version");
        if(version>3) throw new SQLException(LocalText.tr("Непідтримувана версія бази"));
        if(version==1 && migrationBackup!=null) backup(migrationBackup);
        // Existing BASE liabilities remain BASE liabilities; migration never invents physical gold.
        execute("ALTER TABLE currencies ADD COLUMN IF NOT EXISTS backing VARCHAR(16) NOT NULL DEFAULT 'LEGACY_BASE'");
        execute("CREATE TABLE IF NOT EXISTS gold_accounts (owner VARCHAR(100) PRIMARY KEY, balance DECIMAL(38,12) NOT NULL CHECK(balance>=0))");
        execute("CREATE TABLE IF NOT EXISTS gold_ops (id VARCHAR(36) PRIMARY KEY, actor VARCHAR(36), direction VARCHAR(3), target VARCHAR(100), amount INT CHECK(amount>0), status VARCHAR(16), before_items CLOB, after_items CLOB, created BIGINT)");
        execute("CREATE TABLE IF NOT EXISTS currency_log (seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at_time BIGINT, actor VARCHAR(80), code VARCHAR(8), owner VARCHAR(100), event VARCHAR(32), detail CLOB)");
        execute("CREATE INDEX IF NOT EXISTS currency_log_code ON currency_log(code,seq)");
        execute("CREATE INDEX IF NOT EXISTS currency_log_owner ON currency_log(owner,seq)");
        execute("CREATE INDEX IF NOT EXISTS gold_ops_actor ON gold_ops(actor,status)");
        if(version<2) transaction(()->{
            execute("UPDATE currencies SET backing='GOLD' WHERE code<>'BASE' AND supply=0 AND NOT EXISTS(SELECT 1 FROM accounts a WHERE a.owner=CONCAT('r:',currencies.code) AND a.code='BASE' AND a.balance<>0)");
            execute("DELETE FROM schema_version");execute("INSERT INTO schema_version VALUES(2)");return null;
        });

    }
    /** Retire Vault without converting it into city coins or physical gold. Idempotent. */
    public void retireBase() throws SQLException {
        execute("CREATE TABLE IF NOT EXISTS retired_base_accounts(owner VARCHAR(100) PRIMARY KEY,balance BIGINT NOT NULL)");
        execute("CREATE TABLE IF NOT EXISTS retired_base_currencies(code VARCHAR(8) PRIMARY KEY,backing VARCHAR(16),supply BIGINT)");
        transaction(()->{
            for(var row:query("SELECT owner,balance FROM accounts WHERE code='BASE'"))
                execute("MERGE INTO retired_base_accounts KEY(owner) VALUES(?,?)",string(row,"owner"),number(row,"balance"));
            for(var row:query("SELECT code,backing,supply FROM currencies WHERE backing IN('BASE','LEGACY_BASE')"))
                execute("MERGE INTO retired_base_currencies KEY(code) VALUES(?,?,?)",string(row,"code"),string(row,"backing"),number(row,"supply"));
            execute("DELETE FROM accounts WHERE code='BASE'");
            execute("DELETE FROM currencies WHERE code='BASE'");
            // Existing city coins survive with their supply and balances; Vault was not physical gold.
            execute("UPDATE currencies SET backing='GOLD' WHERE backing='LEGACY_BASE'");
            execute("DELETE FROM schema_version");execute("INSERT INTO schema_version VALUES(3)");
            return null;
        });
    }
    @FunctionalInterface public interface Work<T> { T run() throws Exception; }
    public synchronized <T> T transaction(Work<T> work) {
        if (transaction) throw new IllegalStateException(LocalText.tr("Вкладена транзакція"));
        try {
            transaction = true; connection.setAutoCommit(false);
            T result = work.run(); connection.commit(); return result;
        } catch (Exception e) {
            try { connection.rollback(); } catch (SQLException suppressed) { e.addSuppressed(suppressed); }
            if (e instanceof RuntimeException runtime) throw runtime;
            throw new IllegalStateException(LocalText.tr("Не вдалося зберегти зміни"), e);
        } finally {
            transaction = false;
            try { connection.setAutoCommit(true); } catch (SQLException e) { throw new IllegalStateException(e); }
        }
    }
    /** Explicit composition inside one ledger commit; a failed inner action rolls back to its savepoint. */
    public synchronized <T> T atomic(Work<T> work) {
        if(!transaction)return transaction(work);
        Savepoint point=null;
        try {point=connection.setSavepoint();T result=work.run();connection.releaseSavepoint(point);return result;}
        catch(Exception e){
            if(point!=null)try{connection.rollback(point);}catch(SQLException suppressed){e.addSuppressed(suppressed);}
            if(e instanceof RuntimeException runtime)throw runtime;
            throw new IllegalStateException(LocalText.tr("Не вдалося зберегти складену операцію"),e);
        }
    }
    public int execute(String sql, Object... args) throws SQLException {
        try (PreparedStatement statement = prepare(sql, args)) { return statement.executeUpdate(); }
    }
    public List<Map<String,Object>> query(String sql, Object... args) throws SQLException {
        try (PreparedStatement statement = prepare(sql, args); ResultSet rs = statement.executeQuery()) {
            var rows = new ArrayList<Map<String,Object>>();
            while (rs.next()) {
                var row = new LinkedHashMap<String,Object>();
                for (int i=1; i<=rs.getMetaData().getColumnCount(); i++) {
                    Object value = rs.getObject(i);
                    if (value instanceof Clob clob) value = clob.getSubString(1, Math.toIntExact(clob.length()));
                    row.put(rs.getMetaData().getColumnLabel(i).toLowerCase(Locale.ROOT), value);
                }
                rows.add(row);
            }
            return rows;
        }
    }
    public Map<String,Object> one(String sql, Object... args) throws SQLException {
        var rows = query(sql,args); return rows.isEmpty() ? null : rows.get(0);
    }
    private PreparedStatement prepare(String sql, Object... args) throws SQLException {
        PreparedStatement statement = connection.prepareStatement(sql);
        for (int i=0; i<args.length; i++) statement.setObject(i+1,args[i]);
        return statement;
    }
    public static String string(Map<String,Object> row, String key) { return row.get(key)==null ? null : row.get(key).toString(); }
    public static long number(Map<String,Object> row, String key) { return ((Number)row.get(key)).longValue(); }
    public static boolean bool(Map<String,Object> row, String key) { return Boolean.TRUE.equals(row.get(key)); }
    public void backup(String file) throws SQLException {
        // H2 BACKUP writes a consistent online snapshot; never copy an open .mv.db file.
        execute("BACKUP TO '" + file.replace("'", "''") + "'");
    }
    @Override public void close() throws SQLException { connection.close(); }
}
